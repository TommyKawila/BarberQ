#!/usr/bin/env bash
# Concatenate supabase/migrations/*.sql in numeric order.
# Use the output in Supabase SQL Editor on a NEW QA project only — never Production.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
dir="$root/supabase/migrations"
if [[ ! -d "$dir" ]]; then
  echo "Missing $dir" >&2
  exit 1
fi
shopt -s nullglob
files=("$dir"/[0-9][0-9][0-9][0-9]_*.sql)
if [[ ${#files[@]} -eq 0 ]]; then
  echo "No migration files found in $dir" >&2
  exit 1
fi
IFS=$'\n' sorted=($(printf '%s\n' "${files[@]}" | sort))
echo "-- BarberQ schema dump for QA setup"
echo "-- Generated by scripts/concat-migrations.sh"
echo "-- Apply ONLY on a dedicated QA Supabase project."
echo ""
for f in "${sorted[@]}"; do
  base="$(basename "$f")"
  echo "-- ========== BEGIN $base =========="
  cat "$f"
  echo ""
  echo "-- ========== END $base =========="
  echo ""
done
